function [alpha, kappa, theta, beta] = offhooked_coeffs(d0, d1, l1, l2)
%OFFHOOKED_COEFFS  Coefficients of the nilpotent approximation.
%
%   Zuyev & Grushkovskaya, "Stabilization of a Nonholonomic Car Model with
%   Off-Hooked Trailers", arXiv:2403.03341v1, eqs. (11)-(13) and (9).
%
%   Self-test (the paper's own parameter sets):
%       offhooked_coeffs(0.1, 0.1, 1, 1) -> 0.10495 / 0.0024 / 0.0112
%       offhooked_coeffs(1.0, 1.0, 1, 1) -> 1       / 1.5    / 4

    alpha = ( d0^3*( l1^3 + l1^2*l2 - l1*l2^2 - d1*l2*(d1 + l2) ) ...
            + d0*l1^3*( d0*(l1 + 2*l2) + l2*(l1 + l2) ) ) ...
            / ( 2*(d0 + l2)*l1^3 );

    kappa = d0^2*( 1.5*l2^2*(d0 + l1)*(d1 + l1) ...
            - l2*( l1^3 + 0.5*d0*l1^2 - d1*l1*(d0 + 1.5*d1) ...
                   - 1.5*d0*d1^2 ) ...
            + 0.5*d0*d1^2*l1 ) ...
            / ( 3*(d0 + l2)*l1^3 );

    theta = d0^2*( l2^2*(d1 + l1)*(d0 + l1) ...
            + ( d0*d1 + (d0 + d1)*l1 )*d1*l2 ...
            + d0*d1^2*l1 ) ...
            / ( (d0 + l2)*l1^3 );

    beta  = ( d0*l2*( d0^2*(d1 + l1)*(l1 - l2 - d1) ...
            + l1^3*(d0 + l2) ) ) ...
            / ( 6*(d0 + l2)*l1^2 );
end
